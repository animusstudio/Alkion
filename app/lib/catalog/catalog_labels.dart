import 'catalog_bundle.dart';

/// Editorial labels are separate from stable identifiers and search vocabulary.
/// Missing exercise translations fall back to English in CatalogIndex; missing
/// facet labels use an honest localized generic label, never an enum title case.
class CatalogLabels {
  const CatalogLabels(this.locale);
  final String locale;
  int get _language => switch (locale) {
    'it' => 1,
    'de' => 2,
    'es' => 3,
    _ => 0,
  };
  String _label(List<String>? values, String fallback) =>
      values?[_language] ?? fallback;
  String get unknownSetup => [
    'Unspecified setup',
    'Configurazione non specificata',
    'Aufbau nicht angegeben',
    'Configuración sin especificar',
  ][_language];
  String get unknownMuscles => [
    'Muscle information unavailable',
    'Informazioni muscolari non disponibili',
    'Muskelangaben nicht verfügbar',
    'Información muscular no disponible',
  ][_language];
  String get partialMuscles => [
    'Partial muscle information',
    'Informazioni muscolari parziali',
    'Teilweise Muskelangaben',
    'Información muscular parcial',
  ][_language];
  String equipment(String kind) => _label(_equipment[kind], unknownSetup);
  String facet(String field, String value) => _label(
    _facets['$field:$value'] ?? _values[value] ?? _equipment[value],
    unknownSetup,
  );

  /// Show only dimensions necessary to distinguish this variant from the given
  /// candidates. Callers pass the visible siblings, rather than all catalog rows.
  /// Unknown dimensions are never filled from another execution or a family.
  String distinction(
    CatalogVariant variant,
    Iterable<CatalogVariant> siblings,
  ) {
    var remaining = siblings.where((v) => v.id != variant.id).toList();
    if (remaining.isEmpty) return '';
    final fields = [
      'equipment',
      'support',
      'attachment',
      'grip',
      'angle',
      'position',
      'load_mode',
      'laterality',
      'grip_width',
      ...variant.facets.keys.toList()..sort(),
    ];
    final uniqueFields = fields.toSet().toList();
    String? value(CatalogVariant v, String field) =>
        field == 'equipment' ? v.equipmentKind : v.facets[field];
    final parts = <String>[];
    while (remaining.isNotEmpty) {
      String? best;
      var bestRemoved = 0;
      for (final field in uniqueFields) {
        final own = value(variant, field);
        if (own == null) continue;
        final removed = remaining.where((v) => value(v, field) != own).length;
        if (removed > bestRemoved) {
          best = field;
          bestRemoved = removed;
        }
      }
      if (best == null) break;
      final own = value(variant, best)!;
      final label = best == 'equipment' ? equipment(own) : facet(best, own);
      if (!parts.contains(label)) parts.add(label);
      remaining = remaining.where((v) => value(v, best!) == own).toList();
      uniqueFields.remove(best);
    }
    return parts.join(' · ');
  }
}

