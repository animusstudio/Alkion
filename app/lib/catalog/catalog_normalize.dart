/// Lookup policy: Unicode punctuation/symbol separation, fullwidth ASCII,
/// Latin compatibility/case/accent folding and Latin combining marks. This is
/// deliberately not a claim of complete Unicode NFKC outside that repertoire.
const catalogNormalizationPolicy =
    'latin-compat-fullwidth-case-accents-punctuation-v1';

String catalogNormalize(String text, {bool foldAccents = true}) {
  final output = StringBuffer();
  var latinBase = false;
  for (final rune in text.runes) {
    if (_punctuation(rune)) {
      output.write(' ');
      latinBase = false;
      continue;
    }
    if (rune >= 0x300 && rune <= 0x36f && latinBase && foldAccents) continue;
    final char = String.fromCharCode(rune);
    final folded = foldAccents
        ? (_latinCompatibility[char] ?? char.toLowerCase())
        : (rune >= 0xff01 && rune <= 0xff5e
              ? String.fromCharCode(rune - 0xfee0).toLowerCase()
              : char.toLowerCase());
    output.write(folded);
    latinBase = RegExp(r'[a-z]').hasMatch(folded);
  }
  return output.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
}

String catalogLiteralKey(String text) => String.fromCharCodes(
  text.runes.map((r) => r >= 0xff01 && r <= 0xff5e ? r - 0xfee0 : r),
).toLowerCase().replaceAll(RegExp(r'\s+'), ' ').trim();

bool _punctuation(int rune) {
  var low = 0, high = _punctuationRanges.length - 1;
  while (low <= high) {
    final mid = (low + high) ~/ 2, range = _punctuationRanges[mid];
    if (rune < range[0]) {
      high = mid - 1;
    } else if (rune > range[1]) {
      low = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

