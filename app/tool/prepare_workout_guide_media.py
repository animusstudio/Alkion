#!/usr/bin/env python3
"""Verify the offline bundle, or reproduce it from the pinned public checkout.

Default verification needs only Python's standard library. Preparation additionally
needs Pillow/libwebp, whose versions and lossless encoder options are recorded.
No download, catalog lookup, name matching or repository mutation is performed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

APP = Path(__file__).resolve().parents[1]
BUNDLE = APP / "assets/workout_guide"
MANIFEST = BUNDLE / "manifest.json"
RESOLVER = APP / "lib/catalog/catalog_media.dart"
PIN = "aac599224bb9780305239607ef98540b7e0ce389"
NOTICES = {
    "LICENSE-ASSETS": "LICENSE-ASSETS.txt",
    "LICENSE": "LICENSE-CODE.txt",
    "LICENSES.md": "LICENSES.md",
    "ATTRIBUTION.md": "ATTRIBUTION.md",
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def local_path(relative: str) -> Path:
    path = (BUNDLE / relative).resolve()
    if not path.is_relative_to(BUNDLE.resolve()):
        raise ValueError(f"Out-of-bundle path: {relative}")
    return path


def quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def resolver_text(manifest: dict) -> str:
    lines = [
        "// Generated by tool/prepare_workout_guide_media.py from the reviewed manifest.",
        "// Artwork identity is separate from catalog evidence and muscle relationships.",
        "import 'catalog_bundle.dart';", "",
        "const workoutGuideLicenseAsset = 'assets/workout_guide/LICENSE-ASSETS.txt';",
        "const workoutGuideLicenseUrl = 'https://creativecommons.org/licenses/by-sa/4.0/';",
        "",
        "class CatalogExerciseMedia {",
        "  const CatalogExerciseMedia({",
        "    required this.slug,",
        "    required this.frameAssets,",
        "    required this.attribution,",
        "    required this.sourceUrl,",
        "    required this.licenseUrl,",
        "  });", "",
        "  final String slug;",
        "  final List<String> frameAssets;",
        "  final String attribution;",
        "  final String sourceUrl;",
        "  final String licenseUrl;",
        "}", "",
        "/// Exact admitted semantic identity only. Custom choices supply null.",
        "/// Extra/missing facets, changed equipment and future revisions fail closed.",
        "CatalogExerciseMedia? catalogMediaForVariant(CatalogVariant? variant) {",
        "  if (variant == null) return null;",
        "  final entry = _media[variant.key];",
        "  if (entry == null ||",
        "      entry.equipmentKind != variant.equipmentKind ||",
        "      entry.revision != variant.revision ||",
        "      entry.facets.length != variant.facets.length) {",
        "    return null;",
        "  }",
        "  for (final facet in entry.facets.entries) {",
        "    if (variant.facets[facet.key] != facet.value) return null;",
        "  }",
        "  return entry.media;",
        "}", "",
        "class _MediaRegistration {",
        "  const _MediaRegistration({",
        "    required this.equipmentKind,",
        "    required this.facets,",
        "    required this.revision,",
        "    required this.media,",
        "  });", "",
        "  final String equipmentKind;",
        "  final Map<String, String> facets;",
        "  final int revision;",
        "  final CatalogExerciseMedia media;",
        "}", "",
        "const _media = <String, _MediaRegistration>{",
    ]
    for entry in manifest["entries"]:
        credit = "Bryl Lim"
        if entry["upstream_attribution"].get("source"):
            credit += " · Everkinetic"
        source = f"https://github.com/bryllim/workout-guide/tree/{PIN}/packages/workout-guide/assets/{entry['slug']}"
        lines += [
            f"  {quote(entry['variant_key'])}: _MediaRegistration(",
            f"    equipmentKind: {quote(entry['equipment_kind'])},",
            "    facets: {",
            *[f"      {quote(k)}: {quote(v)}," for k, v in sorted(entry["facets"].items())],
            "    },",
            f"    revision: {entry['revision']},",
            "    media: CatalogExerciseMedia(",
            f"      slug: {quote(entry['slug'])},",
            "      frameAssets: [",
            *[f"        {quote('assets/workout_guide/' + f['asset_path'])}," for f in entry["frames"]],
            "      ],",
            f"      attribution: {quote(credit)},",
            f"      sourceUrl: {quote(source)},",
            "      licenseUrl: workoutGuideLicenseUrl,",
            "    ),",
            "  ),",
        ]
    return "\n".join(lines + ["};", ""])


def check_manifest(manifest: dict) -> None:
    if manifest.get("format") != "alkion-workout-guide-media-v1":
        raise ValueError("Unknown manifest format")
    if manifest["upstream"]["commit"] != PIN:
        raise ValueError("Unexpected upstream pin")
    keys, slugs = set(), set()
    for entry in manifest["entries"]:
        key, slug = entry["variant_key"], entry["slug"]
        if key in keys or slug in slugs:
            raise ValueError(f"Duplicate reviewed mapping: {key}/{slug}")
        keys.add(key)
        slugs.add(slug)
        if not entry["frames"] or len(entry["frames"]) > 3:
            raise ValueError(f"Invalid reviewed frame count: {key}")
        indexes = [frame["index"] for frame in entry["frames"]]
        if indexes != sorted(set(indexes)) or not set(indexes) <= {1, 2, 3}:
            raise ValueError(f"Invalid source frame indexes: {key}")
        for frame in entry["frames"]:
            index = frame["index"]
            expected = {
                "master_path": f"masters/{slug}/frame-{index}.svg",
                "asset_path": f"frames/{slug}/frame-{index}.webp",
                "upstream_svg_path": f"assets/{slug}/frame-{index}.svg",
                "upstream_png_path": f"assets/{slug}/frame-{index}.png",
            }
            if any(frame[k] != value for k, value in expected.items()):
                raise ValueError(f"Unexpected frame paths: {key}")
            if (frame["width"], frame["height"]) != (512, 512):
                raise ValueError(f"Unexpected source dimensions: {key}")
            if frame["attribution"]["license"] != "CC BY-SA 4.0":
                raise ValueError(f"Unexpected visual license: {key}")


def prepare(manifest: dict, source: Path) -> None:
    from PIL import Image, __version__ as pillow_version, features

    source = source.resolve()
    commit = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if commit != PIN:
        raise ValueError(f"Expected public source at {PIN}, got {commit}")
    package = source / "packages/workout-guide"
    if digest(package / "manifest.json") != manifest["upstream"]["manifest_sha256"]:
        raise ValueError("Pinned upstream manifest differs")
    upstream = {e["slug"]: e for e in json.loads((package / "manifest.json").read_text())}
    conversion = manifest["conversion"]
    actual_versions = {"pillow_version": pillow_version, "libwebp_version": features.version("webp")}
    for field, value in actual_versions.items():
        if conversion.get(field, value) != value:
            raise ValueError(f"Reproduction needs {field}={conversion[field]}, got {value}")
        conversion[field] = value
    for entry in manifest["entries"]:
        original = upstream[entry["slug"]]
        if entry["upstream_attribution"] != original["attribution"]:
            raise ValueError(f"Changed exercise attribution: {entry['slug']}")
        for frame in entry["frames"]:
            original_frame = next(f for f in original["frames"] if f["index"] == frame["index"])
            if frame["attribution"] != original_frame["attribution"]:
                raise ValueError(f"Changed frame attribution: {entry['slug']}")
            svg, png = package / frame["upstream_svg_path"], package / frame["upstream_png_path"]
            if digest(svg) != frame["svg_sha256"] or digest(png) != frame["png_sha256"]:
                raise ValueError(f"Changed pinned source frame: {png}")
            master, asset = local_path(frame["master_path"]), local_path(frame["asset_path"])
            master.parent.mkdir(parents=True, exist_ok=True)
            asset.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(svg, master)
            with Image.open(png) as image:
                rgba = image.convert("RGBA")
                if rgba.size != (512, 512) or rgba.getextrema()[3][0] != 0:
                    raise ValueError(f"Expected transparent 512px source: {png}")
                rgba.save(asset, format="WEBP", lossless=True, exact=True, method=6)
                with Image.open(asset) as converted:
                    if converted.convert("RGBA").tobytes() != rgba.tobytes():
                        raise ValueError(f"Lossless pixel roundtrip failed: {asset}")
            frame["asset_sha256"] = digest(asset)
            frame["asset_bytes"] = asset.stat().st_size
            frame["svg_bytes"] = master.stat().st_size
    manifest["notices"] = []
    for original, target in NOTICES.items():
        shutil.copyfile(source / original, BUNDLE / target)
        manifest["notices"].append({"path": target, "upstream_path": original, "sha256": digest(BUNDLE / target)})
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    RESOLVER.write_text(resolver_text(manifest))


def dart_resolver_tokens(source: str) -> tuple[str, ...]:
    """Compare generated Dart tokens while retaining every byte inside literals.

    The generator emits ordinary non-interpolated literals. Reject interpolation
    rather than attempting to interpret nested Dart expressions inside a string.
    Trailing commas in its constructor arguments, lists and maps are optional.
    """
    tokens: list[str] = []
    operators = (
        ">>>=", "...", "??=", ">>=", "<<=", "~/=", ">>>", "?.", "??",
        "=>", "==", "!=", "<=", ">=", "&&", "||", "++", "--", "+=",
        "-=", "*=", "/=", "%=", "&=", "|=", "^=", "<<", ">>", "~/",
    )
    index = 0
    while index < len(source):
        start = index
        if source[index].isspace():
            index += 1
            continue
        if source.startswith("//", index):
            end = source.find("\n", index + 2)
            index = len(source) if end == -1 else end + 1
            continue
        if source.startswith("/*", index):
            depth = 1
            index += 2
            while depth and index < len(source):
                if source.startswith("/*", index):
                    depth += 1
                    index += 2
                elif source.startswith("*/", index):
                    depth -= 1
                    index += 2
                else:
                    index += 1
            if depth:
                raise ValueError("Unterminated Dart resolver comment")
            continue
        raw = source[index] == "r" and source[index:index + 2] in ("r'", 'r"')
        quote_index = index + 1 if raw else index
        if source[quote_index] in ("'", '"'):
            quote_char = source[quote_index]
            delimiter = quote_char * (3 if source.startswith(quote_char * 3, quote_index) else 1)
            index = quote_index + len(delimiter)
            while index < len(source):
                if source.startswith(delimiter, index):
                    index += len(delimiter)
                    tokens.append(source[start:index])
                    break
                if not raw and source[index] == "\\":
                    index += 2
                    continue
                if not raw and source[index] == "$":
                    raise ValueError("Interpolated Dart resolver strings are unsupported")
                if len(delimiter) == 1 and source[index] in "\r\n":
                    raise ValueError("Unterminated Dart resolver string")
                index += 1
            else:
                raise ValueError("Unterminated Dart resolver string")
            continue
        if source[index].isalnum() or source[index] in "_$":
            index += 1
            while index < len(source) and (source[index].isalnum() or source[index] in "_$"):
                index += 1
            tokens.append(source[start:index])
            continue
        operator = next((op for op in operators if source.startswith(op, index)), None)
        if operator is not None:
            tokens.append(operator)
            index += len(operator)
        else:
            tokens.append(source[index])
            index += 1
    return tuple(
        token for index, token in enumerate(tokens)
        if not (token == "," and index + 1 < len(tokens) and tokens[index + 1] in (")", "]", "}"))
    )


def verify(manifest: dict) -> None:
    paths = set()
    total_bytes = 0
    for entry in manifest["entries"]:
        for frame in entry["frames"]:
            master, asset = local_path(frame["master_path"]), local_path(frame["asset_path"])
            for path, expected_hash, expected_bytes in [
                (master, frame["svg_sha256"], frame["svg_bytes"]),
                (asset, frame["asset_sha256"], frame["asset_bytes"]),
            ]:
                if digest(path) != expected_hash or path.stat().st_size != expected_bytes:
                    raise ValueError(f"Asset integrity mismatch: {path}")
                paths.add(path)
                total_bytes += path.stat().st_size
            svg = ET.parse(master).getroot()
            if svg.attrib.get("viewBox") != "0 0 512 512":
                raise ValueError(f"Unexpected SVG canvas: {master}")
            if [n.tag.rsplit("}", 1)[-1] for n in svg.iter()] != ["svg", "path"]:
                raise ValueError(f"Unexpected SVG complexity: {master}")
            data = asset.read_bytes()
            if data[:4] != b"RIFF" or data[8:12] != b"WEBP" or data[12:16] != b"VP8L":
                raise ValueError(f"Expected lossless WebP frame: {asset}")
    pubspec = (APP / "pubspec.yaml").read_text()
    for slug in {entry["slug"] for entry in manifest["entries"]}:
        if f"    - assets/workout_guide/frames/{slug}/\n" not in pubspec:
            raise ValueError(f"Missing runtime asset declaration: {slug}")
    if "    - assets/workout_guide/\n" in pubspec or "    - assets/workout_guide/masters/" in pubspec:
        raise ValueError("SVG masters must remain outside runtime asset declarations")
    actual = {p.resolve() for folder in (BUNDLE / "frames", BUNDLE / "masters") for p in folder.rglob("*") if p.is_file()}
    if actual != paths:
        raise ValueError("Missing or unmanifested media assets")
    for notice in manifest["notices"]:
        if digest(local_path(notice["path"])) != notice["sha256"]:
            raise ValueError(f"Notice integrity mismatch: {notice['path']}")
    # Formatting may change code whitespace, comments and optional trailing commas.
    # Quoted contents and every other token must still match the reviewed source.
    if dart_resolver_tokens(RESOLVER.read_text()) != dart_resolver_tokens(resolver_text(manifest)):
        raise ValueError("Resolver no longer matches reviewed manifest")
    print(f"PASS: {len(manifest['entries'])} exact mappings, {sum(len(e['frames']) for e in manifest['entries'])} frames, {total_bytes:,} source/runtime bytes; hashes, notices and resolver agree")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Reproduce from an existing pinned Workout Guide checkout")
    args = parser.parse_args()
    try:
        manifest = json.loads(MANIFEST.read_text())
        check_manifest(manifest)
        if args.source:
            prepare(manifest, args.source)
        verify(manifest)
    except (OSError, ValueError, KeyError, StopIteration, subprocess.CalledProcessError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
